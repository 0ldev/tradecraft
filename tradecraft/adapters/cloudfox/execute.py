"""
Execution logic for cloudfox: situational awareness and attack path identification
for cloud environments (AWS, Azure, GCP).
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional

DEFAULT_TIMEOUT_SECONDS = 180


@dataclass
class RawCloudfoxResult:
    stdout: str = ""
    stderr: str = ""
    returncode: int = 0
    provider: str = ""
    command: str = ""
    json_data: List[Dict[str, Any]] = field(default_factory=list)
    error: Optional[str] = None


def find_binary() -> Optional[str]:
    """Finds cloudfox binary on PATH."""
    return shutil.which("cloudfox")


def build_argv(
    provider: str,
    command: str = "all-checks",
    target: str = "",
    credentials: str = "",
    out_dir: str = "",
    binary: str = "cloudfox",
) -> List[str]:
    """
    Builds cloudfox execution argv.
    cloudfox <provider> <command> [flags]
    """
    cmd = [binary, provider.strip().lower(), command.strip()]
    if out_dir:
        cmd.extend(["-o", out_dir])
    return cmd


def execute(
    provider: str = "aws",
    command: str = "permissions",
    target: str = "",
    credentials: str = "",
    timeout: int = DEFAULT_TIMEOUT_SECONDS,
) -> RawCloudfoxResult:
    """Executes cloudfox analysis for a given cloud provider."""
    p = provider.strip().lower()
    if p not in ("aws", "azure", "gcp"):
        return RawCloudfoxResult(error=f"unsupported cloud provider '{provider}', must be aws, azure, or gcp")

    binary = find_binary()
    if not binary:
        return RawCloudfoxResult(provider=p, command=command, error="cloudfox executable not found on PATH")

    with tempfile.TemporaryDirectory(prefix="cloudfox_out_") as tmpdir:
        argv = build_argv(
            provider=p,
            command=command or "permissions",
            target=target,
            credentials=credentials,
            out_dir=tmpdir,
            binary=binary,
        )

        env = dict(os.environ)
        if credentials.strip() and p == "aws":
            parts = credentials.split(":")
            if len(parts) >= 2:
                env["AWS_ACCESS_KEY_ID"] = parts[0].strip()
                env["AWS_SECRET_ACCESS_KEY"] = parts[1].strip()
                if len(parts) >= 3 and parts[2].strip():
                    env["AWS_SESSION_TOKEN"] = parts[2].strip()

        try:
            proc = subprocess.run(
                argv,
                capture_output=True,
                text=True,
                timeout=timeout,
                stdin=subprocess.DEVNULL,
                env=env,
            )

            # Look for any json output files generated by cloudfox in tmpdir
            json_data: List[Dict[str, Any]] = []
            for jfile in Path(tmpdir).rglob("*.json"):
                try:
                    content = json.loads(jfile.read_text(encoding="utf-8", errors="replace"))
                    if isinstance(content, list):
                        json_data.extend(content)
                    elif isinstance(content, dict):
                        json_data.append(content)
                except Exception:
                    pass

            return RawCloudfoxResult(
                stdout=proc.stdout or "",
                stderr=proc.stderr or "",
                returncode=proc.returncode,
                provider=p,
                command=command,
                json_data=json_data,
            )
        except FileNotFoundError:
            return RawCloudfoxResult(provider=p, command=command, error="cloudfox binary not found on PATH")
        except subprocess.TimeoutExpired:
            return RawCloudfoxResult(provider=p, command=command, error=f"cloudfox timed out after {timeout}s")
        except Exception as exc:
            return RawCloudfoxResult(provider=p, command=command, error=f"cloudfox execution failed: {exc}")
